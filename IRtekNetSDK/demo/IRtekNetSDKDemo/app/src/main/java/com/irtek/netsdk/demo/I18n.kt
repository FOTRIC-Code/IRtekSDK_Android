package com.irtek.netsdk.demo

import android.content.Context
import java.util.Locale

enum class AppLang { EN, ZH }

private const val PREF_FILE = "demo_prefs"
private const val PREF_LANG = "app_lang"

fun loadAppLang(context: Context): AppLang {
    val v = context.getSharedPreferences(PREF_FILE, Context.MODE_PRIVATE).getString(PREF_LANG, "en")
    return if (v == "zh") AppLang.ZH else AppLang.EN
}

fun saveAppLang(context: Context, lang: AppLang) {
    context.getSharedPreferences(PREF_FILE, Context.MODE_PRIVATE)
        .edit()
        .putString(PREF_LANG, if (lang == AppLang.ZH) "zh" else "en")
        .apply()
}

